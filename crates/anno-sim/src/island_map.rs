    /// Live source map-object kind at a type-3 civilian route endpoint.
    pub fn civilian_path_kind(&self, position: (i32, i32)) -> Option<u8> {
        self.civilian_path_cell(position).map(|cell| cell.kind_code)
    }

    /// Target-cell predicate used by the type-4 native idle branch. Its
    /// source check accepts runtime kind codes `1` and `11`; kind `1` covers
    /// the executable's road and production-label aliases.
    pub fn source_native_idle_target_allowed(&self, position: (i32, i32)) -> bool {
        matches!(self.civilian_path_kind(position), Some(1 | 11))
    }

    /// Source map-cell terrain elevation used to initialise a figure's Z
    /// coordinate. This is `Posoffs × 0.028` after INSELHAUS replay.
    pub fn source_terrain_height(&self, position: (i32, i32)) -> Option<f32> {
        let (x, y) = position;
        if x < 0 || y < 0 || x >= i32::from(self.width) || y >= i32::from(self.height) {
            return None;
        }
        self.source_terrain_heights
            .get(y as usize * self.width as usize + x as usize)
            .copied()
    }

    fn movement_speed(&self, speeds: &[u16], position: (i32, i32)) -> Option<u16> {
        let (x, y) = position;
        if x < 0 || y < 0 || x >= i32::from(self.width) || y >= i32::from(self.height) {
            return None;
        }
        speeds
            .get(y as usize * self.width as usize + x as usize)
            .copied()
            .filter(|speed| *speed != 0)
    }

    fn civilian_path_cell(&self, position: (i32, i32)) -> Option<SourceCivilianPathCell> {
        self.civilian_path_cells
            .get(self.local_index(position)?)
            .copied()
            .flatten()
    }

    fn source_map_kind_cell(&self, position: (i32, i32)) -> Option<SourceMapKindCell> {
        self.source_map_kind_cells
            .get(self.local_index(position)?)
            .copied()
            .flatten()
    }

    fn local_index(&self, position: (i32, i32)) -> Option<usize> {
        self.contains_local(position.0, position.1)
            .then_some(position.1 as usize * self.width as usize + position.0 as usize)
    }

    /// Mark a tile as walkable (e.g., for warehouse placement after map creation).
    pub fn set_walkable(&mut self, x: u16, y: u16, val: bool) {
        if x < self.width && y < self.height {
            self.walkable[y as usize * self.width as usize + x as usize] = val;
        }
    }

    /// A tile is "coastal" if it's walkable AND at least one of its
    /// 4-neighbours is out of bounds — i.e. it sits on the perimeter of
    /// the island's walkable region. Fisheries can only go on coastal tiles.
    pub fn is_coastal(&self, x: i32, y: i32) -> bool {
        if !self.is_walkable(x, y) {
            return false;
        }
        for (dx, dy) in [(1i32, 0i32), (-1, 0), (0, 1), (0, -1)] {
            let nx = x + dx;
            let ny = y + dy;
            if nx < 0 || ny < 0 || nx >= self.width as i32 || ny >= self.height as i32 {
                return true;
            }
        }
        false
    }

    /// True iff the entire `w × h` footprint anchored at `(x, y)` is walkable.
    pub fn can_fit(&self, x: i32, y: i32, w: u16, h: u16) -> bool {
        if x < 0 || y < 0 {
            return false;
        }
        if (x as u32) + w as u32 > self.width as u32 {
            return false;
        }
        if (y as u32) + h as u32 > self.height as u32 {
            return false;
        }
        for dy in 0..h as i32 {
            for dx in 0..w as i32 {
                if !self.is_walkable(x + dx, y + dy) {
                    return false;
                }
            }
        }
        true
    }

    /// Spiral search around `(cx, cy)` (warehouse, typically) for the first
    /// position where `w × h` fits. Returns top-left tile or None.
    pub fn find_open_spot(
        &self,
        cx: u16,
        cy: u16,
        w: u16,
        h: u16,
        max_radius: u16,
    ) -> Option<(u16, u16)> {
        for r in 0..=max_radius as i32 {
            for dy in -r..=r {
                for dx in -r..=r {
                    // Only the ring at the current radius (skip interior).
                    if dx.abs() != r && dy.abs() != r {
                        continue;
                    }
                    let x = cx as i32 + dx;
                    let y = cy as i32 + dy;
                    if self.can_fit(x, y, w, h) {
                        return Some((x as u16, y as u16));
                    }
                }
            }
        }
        None
    }

    /// Like `find_open_spot`, but additionally rejects candidates that
    /// aren't reachable from `anchor` via the walkability graph (BFS).
    /// `anchor` is normally the warehouse tile that will service the new
    /// building. Use this when placement requires a carrier route home.
    pub fn find_reachable_spot(
        &self,
        cx: u16,
        cy: u16,
        w: u16,
        h: u16,
        max_radius: u16,
        anchor: (u16, u16),
    ) -> Option<(u16, u16)> {
        for r in 0..=max_radius as i32 {
            for dy in -r..=r {
                for dx in -r..=r {
                    if dx.abs() != r && dy.abs() != r {
                        continue;
                    }
                    let x = cx as i32 + dx;
                    let y = cy as i32 + dy;
                    if !self.can_fit(x, y, w, h) {
                        continue;
                    }
                    if self.reachable((anchor.0 as i32, anchor.1 as i32), (x, y)) {
                        return Some((x as u16, y as u16));
                    }
                }
            }
        }
        None
    }

    /// 4-directional BFS reachability check; cap node visits so a giant
    /// island doesn't make this dominate the AI tick. Returns true when
    /// `goal` is connected to `start` via walkable tiles. If `start`
    /// itself isn't walkable (e.g. it's a warehouse anchor whose footprint
    /// is non-walkable), falls back to the nearest walkable 4-neighbour.
    pub fn reachable(&self, start: (i32, i32), goal: (i32, i32)) -> bool {
        if start == goal {
            return true;
        }
        let start = if self.is_walkable(start.0, start.1) {
            start
        } else {
            let mut alt = None;
            for (dx, dy) in [(1, 0), (-1, 0), (0, 1), (0, -1)] {
                let n = (start.0 + dx, start.1 + dy);
                if self.is_walkable(n.0, n.1) {
                    alt = Some(n);
                    break;
                }
            }
            match alt {
                Some(p) => p,
                None => return false,
            }
        };
        if !self.is_walkable(goal.0, goal.1) {
            return false;
        }
        const NODE_BUDGET: usize = 4_096;
        let mut visited = std::collections::HashSet::new();
        let mut queue = std::collections::VecDeque::new();
        visited.insert(start);
        queue.push_back(start);
        while let Some((x, y)) = queue.pop_front() {
            if visited.len() > NODE_BUDGET {
                return false;
            }
            for (dx, dy) in [(1i32, 0i32), (-1, 0), (0, 1), (0, -1)] {
                let n = (x + dx, y + dy);
                if !self.is_walkable(n.0, n.1) {
                    continue;
                }
                if !visited.insert(n) {
                    continue;
                }
                if n == goal {
                    return true;
                }
                queue.push_back(n);
            }
        }
        false
    }

