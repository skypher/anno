    /// `FUN_0040e8b0`'s raw suitability score for one map-owner selector.
    /// The controller initializer compares these unnormalised scores when no
    /// owned city has at least ten inhabitants in BGRUPPE tiers 2 through 4.
    pub fn source_controller_city_suitability_score(&self, owner: u8) -> i32 {
        let mut score = i32::from(self.width) * i32::from(self.height);
        for cell in &self.source_map_kind_cells {
            let penalty = match cell {
                Some(cell) if cell.map_owner == 7 || cell.map_owner == owner => {
                    match cell.kind_code {
                        10..=12 => 4,
                        25 | 26 => 2,
                        _ => 1,
                    }
                }
                _ => 1,
            };
            score -= penalty;
        }
        score
    }

    /// Replay `FUN_00415af0` over this island's live source kind and owner
    /// grid. The executable scans its half-open `(0, 0)` through
    /// `(width - 1, height - 1)` bounds, first marking vertical runs and then
    /// merging horizontal runs from consecutive rows into six-word records.
    pub fn source_controller_city_rectangles(
        &self,
        owner: u8,
        minimum_width: u16,
        minimum_height: u16,
    ) -> Vec<SourceControllerCityRectangle> {
        let x_limit = usize::from(self.width.saturating_sub(1));
        let y_limit = usize::from(self.height.saturating_sub(1));
        let minimum_width = usize::from(minimum_width);
        let minimum_height = usize::from(minimum_height);
        if x_limit == 0 || y_limit == 0 || minimum_width == 0 || minimum_height == 0 {
            return Vec::new();
        }

        let mut marked = vec![false; usize::from(self.width) * usize::from(self.height)];
        let eligible = |x: usize, y: usize| {
            self.source_map_kind_cells[y * usize::from(self.width) + x].is_some_and(|cell| {
                cell.map_owner == owner && matches!(cell.kind_code, 10..=12 | 31 | 32)
            })
        };

        for x in 0..x_limit {
            let mut run_start = 0;
            let mut run_length = 0;
            for y in 0..y_limit {
                if eligible(x, y) {
                    if run_length == 0 {
                        run_start = y;
                    }
                    run_length += 1;
                    continue;
                }
                if run_length >= minimum_height {
                    for marked_y in run_start..run_start + run_length {
                        marked[marked_y * usize::from(self.width) + x] = true;
                    }
                }
                run_length = 0;
            }
        }

        let mut rectangles = Vec::new();
        let mut previous_lines: Vec<(usize, usize, usize)> = Vec::new();
        for y in 0..y_limit {
            let mut current_lines = Vec::new();
            let mut run_start = 0;
            let mut run_length = 0;
            for x in 0..x_limit {
                if marked[y * usize::from(self.width) + x] {
                    if run_length == 0 {
                        run_start = x;
                    }
                    run_length += 1;
                    continue;
                }
                if run_length != 0 {
                    for marked_x in run_start..run_start + run_length {
                        marked[y * usize::from(self.width) + marked_x] = false;
                    }
                    if run_length >= minimum_width {
                        let run_end = run_start + run_length;
                        let rectangle = previous_lines
                            .iter()
                            .find(|(previous_start, previous_end, _)| {
                                run_start <= *previous_end && *previous_start <= run_end
                            })
                            .map(|(_, _, rectangle)| *rectangle)
                            .unwrap_or_else(|| {
                                if rectangles.len() == 256 {
                                    return usize::MAX;
                                }
                                rectangles.push(SourceControllerCityRectangle {
                                    x0: run_start as u16,
                                    y0: y as u16,
                                    x1: run_end as u16,
                                    y1: y as u16 + 1,
                                    area: 0,
                                });
                                rectangles.len() - 1
                            });
                        if rectangle != usize::MAX {
                            let entry = &mut rectangles[rectangle];
                            entry.x0 = entry.x0.min(run_start as u16);
                            entry.x1 = entry.x1.max(run_end as u16);
                            entry.y1 = y as u16 + 1;
                            entry.area = entry.area.saturating_add(run_length as u32);
                            current_lines.push((run_start, run_end, rectangle));
                        }
                    }
                }
                run_length = 0;
            }
            previous_lines = current_lines;
        }
        rectangles
    }

    /// Replay `FUN_004160c0` for one expanded action-three rectangle. The
    /// first source pass emits vertical segments, then the second emits
    /// horizontal segments, each capped at 256 records in total.
    pub fn source_controller_city_candidate_segments(
        &self,
        owner: u8,
        x0: i32,
        y0: i32,
        x1: i32,
        y1: i32,
        minimum_horizontal_length: u32,
        minimum_vertical_length: u32,
    ) -> Vec<SourceControllerCityCandidateSegment> {
        let mut segments = Vec::new();
        for x in x0..x1 {
            let mut run_start = 0;
            let mut run_length = 0_u32;
            for y in y0..y1 {
                let Some(cell) = self.source_map_kind_cell((x, y)) else {
                    continue;
                };
                if cell.map_owner != owner {
                    continue;
                }
                if source_controller_city_candidate_kind(cell.kind_code)
                    && self.source_controller_city_horizontal_clear(x, y)
                {
                    if run_length == 0 {
                        run_start = y;
                    }
                    run_length = run_length.saturating_add(1);
                    continue;
                }
                if run_length >= minimum_vertical_length && segments.len() < 256 {
                    segments.push(SourceControllerCityCandidateSegment {
                        x0: x,
                        y0: run_start,
                        x1: x,
                        y1: run_start + run_length as i32,
                        length: run_length,
                    });
                }
                run_length = 0;
            }
        }
        for y in y0..y1 {
            let mut run_start = 0;
            let mut run_length = 0_u32;
            for x in x0..x1 {
                let Some(cell) = self.source_map_kind_cell((x, y)) else {
                    continue;
                };
                if cell.map_owner != owner {
                    continue;
                }
                if source_controller_city_candidate_kind(cell.kind_code)
                    && self.source_controller_city_vertical_clear(x, y)
                {
                    if run_length == 0 {
                        run_start = x;
                    }
                    run_length = run_length.saturating_add(1);
                    continue;
                }
                if run_length >= minimum_horizontal_length && segments.len() < 256 {
                    segments.push(SourceControllerCityCandidateSegment {
                        x0: run_start,
                        y0: y,
                        x1: run_start + run_length as i32,
                        y1: y,
                        length: run_length,
                    });
                }
                run_length = 0;
            }
        }
        segments
    }

    fn source_controller_city_horizontal_clear(&self, x: i32, y: i32) -> bool {
        let left = x.min(6);
        for offset in -left..-3 {
            if !self.source_controller_city_clearance_kind((x + offset, y)) {
                return false;
            }
        }
        let right = (i32::from(self.width) - x).min(6);
        for offset in 3..right {
            if !self.source_controller_city_clearance_kind((x + offset, y)) {
                return false;
            }
        }
        true
    }

    fn source_controller_city_vertical_clear(&self, x: i32, y: i32) -> bool {
        let above = y.min(6);
        for offset in -above..-3 {
            if !self.source_controller_city_clearance_kind((x, y + offset)) {
                return false;
            }
        }
        let below = (i32::from(self.height) - y).min(6);
        for offset in 3..below {
            if !self.source_controller_city_clearance_kind((x, y + offset)) {
                return false;
            }
        }
        true
    }

    fn source_controller_city_clearance_kind(&self, position: (i32, i32)) -> bool {
        self.source_map_kind_cell(position)
            .map(|cell| matches!(cell.kind_code, 10..=12 | 19))
            .unwrap_or(true)
    }

    /// `FUN_00417220` with the state-three `param_4 = 1` look-ahead. The
    /// source follows the selected cell's two-bit map direction, skips eight
    /// cells, then accepts only if no remaining cell in that ray has kind 19.
    pub fn source_controller_city_boundary_clear(&self, x: i32, y: i32) -> bool {
        let Some(cell) = self.source_map_kind_cell((x, y)) else {
            return false;
        };
        let (step_x, step_y, available) = match cell.map_direction {
            0 => (0, 1, i32::from(self.height) - y - 1),
            1 => (-1, 0, x),
            2 => (0, -1, y),
            _ => (1, 0, i32::from(self.width) - x - 1),
        };
        let mut position = (x + step_x * 8, y + step_y * 8);
        let mut remaining = available - 2;
        while remaining > 0 {
            remaining -= 1;
            let Some(cell) = self.source_map_kind_cell(position) else {
                // The executable's map allocation includes sea padding beyond
                // this local island grid.
                return true;
            };
            if cell.kind_code != 19 {
                return false;
            }
            position.0 += step_x;
            position.1 += step_y;
        }
        true
    }

    /// `FUN_0040fe80` from one local map cell and a two-bit direction. The
    /// return is the source's one-based line distance, including its special
    /// single-kind-16 run handling.
    pub fn source_controller_city_line_distance(
        &self,
        owner: u8,
        x: i32,
        y: i32,
        direction: u8,
    ) -> u32 {
        let (step_x, step_y, mut remaining) = match direction & 3 {
            0 => (1, 0, i32::from(self.width) - x - 1),
            1 => (0, 1, i32::from(self.height) - y - 1),
            2 => (-1, 0, x),
            _ => (0, -1, y),
        };
        let mut position = (x, y);
        let mut prior_was_kind_16 = false;
        let mut distance = 1_u32;
        while remaining > 0 {
            remaining -= 1;
            position.0 += step_x;
            position.1 += step_y;
            let Some(cell) = self.source_map_kind_cell(position) else {
                return distance;
            };
            if cell.map_owner != owner && cell.map_owner != 7 {
                return distance;
            }
            if cell.kind_code == 16 && !prior_was_kind_16 {
                prior_was_kind_16 = true;
            } else if matches!(cell.kind_code, 1 | 4 | 10..=12 | 18) {
                prior_was_kind_16 = false;
            } else {
                return if distance < 2 { 0 } else { distance };
            }
            distance = distance.saturating_add(1);
        }
        distance
    }

