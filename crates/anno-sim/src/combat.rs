/// `FUN_004581f0` initializes the normal route window at `start - r`. Once
/// runtime byte `+0x22` is nonzero, it draws `rand() & 3` and uses one of four
/// origins offset by `r / 2` or `r + r / 2` on each axis.
fn source_kind4_route_window_center(
    start: (i32, i32),
    route_radius: u8,
    retry_count: u8,
    source_rand: &mut SourceRand,
) -> Option<(i32, i32)> {
    let radius = i32::from(route_radius);
    if retry_count == 0 {
        return Some(start);
    }

    let near_offset = radius / 2;
    let far_offset = near_offset.checked_add(radius)?;
    let (x_offset, y_offset) = match source_rand.next() & 3 {
        0 => (near_offset, near_offset),
        1 => (far_offset, near_offset),
        2 => (far_offset, far_offset),
        _ => (near_offset, far_offset),
    };
    Some((
        start.0.checked_sub(x_offset)?.checked_add(radius)?,
        start.1.checked_sub(y_offset)?.checked_add(radius)?,
    ))
}

