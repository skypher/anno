fn next_step_to(
    unit: &MilitaryUnit,
    target: (i32, i32),
    ocean_map: Option<&crate::ocean_map::OceanMap>,
    island_maps: &[crate::island_map::IslandMap],
) -> Option<(i32, i32)> {
    if (unit.tile_x, unit.tile_y) == target {
        return None;
    }

    if unit.unit_type.stats().is_naval {
        let next = direct_step_toward((unit.tile_x, unit.tile_y), target)?;
        if let Some(om) = ocean_map {
            if !om.is_navigable(next.0, next.1) {
                return None;
            }
        }
        return Some(next);
    }

    if let Some(island_id) = unit.source_island_id {
        let map = island_maps.iter().find(|map| map.island_id == island_id)?;
        let start = map.source_world_to_local((unit.tile_x, unit.tile_y))?;
        let target_local = map.source_world_to_local(target)?;
        if start == target_local {
            return direct_step_toward((unit.tile_x, unit.tile_y), target);
        }
        return crate::pathfinding::find_path(map, start, target_local)
            .and_then(|path| path.first().copied())
            .and_then(|local| map.local_to_source_world(local))
            .and_then(|waypoint| direct_step_toward((unit.tile_x, unit.tile_y), waypoint));
    }

    if let Some(map) = island_maps
        .iter()
        .find(|m| m.is_walkable(unit.tile_x, unit.tile_y))
    {
        return crate::pathfinding::find_path(map, (unit.tile_x, unit.tile_y), target)
            .and_then(|path| path.first().copied());
    }

    direct_step_toward((unit.tile_x, unit.tile_y), target)
}

fn direct_step_toward(start: (i32, i32), target: (i32, i32)) -> Option<(i32, i32)> {
    let dx = target.0 - start.0;
    let dy = target.1 - start.1;
    if dx == 0 && dy == 0 {
        return None;
    }
    let sx = dx.signum();
    let sy = dy.signum();
    if dx.abs() > 0 && dy.abs() > 0 {
        Some((start.0 + sx, start.1 + sy))
    } else if dx.abs() > 0 {
        Some((start.0 + sx, start.1))
    } else {
        Some((start.0, start.1 + sy))
    }
}

/// Find the nearest enemy unit within detection range.
fn find_nearest_enemy(
    units: &[MilitaryUnit],
    unit_idx: usize,
    diplomacy: &DiplomacyMatrix,
    island_maps: &[crate::island_map::IslandMap],
) -> Option<usize> {
    let unit = &units[unit_idx];
    let detection_sq = DETECTION_RANGE * DETECTION_RANGE;
    let mut best_dist = u32::MAX;
    let mut best_idx = None;

    for (j, other) in units.iter().enumerate() {
        if j == unit_idx || !other.is_alive() {
            continue;
        }

        // Check diplomacy
        if diplomacy.get(unit.owner, other.owner) != Diplomacy::War {
            continue;
        }

        // Check naval/land compatibility
        let unit_stats = unit.unit_type.stats();
        let other_stats = other.unit_type.stats();
        if unit_stats.is_naval != other_stats.is_naval {
            continue; // Ships can't attack land units and vice versa
        }

        let dist = unit_distance_sq(unit, other, island_maps);
        if dist <= detection_sq && dist < best_dist {
            best_dist = dist;
            best_idx = Some(j);
        }
    }

    best_idx
}

/// Distance in combat cells. Type-4 figures retain doubled source-world
/// positions, while their combat and detection values are expressed in
/// INSEL5 local cells. Figures from different source islands, and all
/// non-source pairs, retain the existing world-coordinate metric.
fn unit_distance_sq(
    first: &MilitaryUnit,
    second: &MilitaryUnit,
    island_maps: &[crate::island_map::IslandMap],
) -> u32 {
    if let (Some(first_island), Some(second_island)) =
        (first.source_island_id, second.source_island_id)
    {
        if first_island == second_island {
            if let Some(map) = island_maps.iter().find(|map| map.island_id == first_island) {
                if let (Some((first_x, first_y)), Some((second_x, second_y))) = (
                    map.source_world_to_local((first.tile_x, first.tile_y)),
                    map.source_world_to_local((second.tile_x, second.tile_y)),
                ) {
                    return distance_sq(first_x, first_y, second_x, second_y);
                }
            }
        }
    }
    distance_sq(first.tile_x, first.tile_y, second.tile_x, second.tile_y)
}

/// Calculate the expected outcome of a battle between two unit groups.
/// Returns (attacker_surviving_health_ratio, defender_surviving_health_ratio).
pub fn simulate_battle_outcome(
    attackers: &[(UnitType, u32)],
    defenders: &[(UnitType, u32)],
) -> (f32, f32) {
    let mut attacker_hp: f32 = attackers
        .iter()
        .map(|(t, n)| t.stats().max_health * *n as f32)
        .sum();
    let mut defender_hp: f32 = defenders
        .iter()
        .map(|(t, n)| t.stats().max_health * *n as f32)
        .sum();

    let attacker_dps: f32 = attackers
        .iter()
        .map(|(t, n)| {
            let s = t.stats();
            s.attack_damage / (s.attack_speed_ms as f32 / 1000.0) * *n as f32
        })
        .sum();
    let defender_dps: f32 = defenders
        .iter()
        .map(|(t, n)| {
            let s = t.stats();
            s.attack_damage / (s.attack_speed_ms as f32 / 1000.0) * *n as f32
        })
        .sum();

    let total_attacker_hp = attacker_hp;
    let total_defender_hp = defender_hp;

    // Simple Lanchester model: each side deals DPS to the other until one is eliminated
    let dt = 0.1f32; // 100ms steps
    for _ in 0..1000 {
        if attacker_hp <= 0.0 || defender_hp <= 0.0 {
            break;
        }
        attacker_hp -= defender_dps * dt;
        defender_hp -= attacker_dps * dt;
    }

    (
        (attacker_hp.max(0.0) / total_attacker_hp),
        (defender_hp.max(0.0) / total_defender_hp),
    )
}

