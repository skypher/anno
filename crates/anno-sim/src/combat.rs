/// `FUN_00446ca0` initializes byte zero of each newly allocated type-4
/// runtime slot to `0x2d`; `FUN_004581f0` uses that byte as its raw-grid
/// route radius.
pub const SOURCE_KIND4_DEFAULT_ROUTE_RADIUS: u8 = 0x2d;
/// `SOLDAT3` runtime bytes `+0x130..+0x1af` hold the packed route program
/// generated by `FUN_004581f0` and consumed by `FUN_00457ce0`.
pub const SOURCE_KIND4_ROUTE_PROGRAM_CAPACITY: usize = 0x80;
pub const SOURCE_KIND4_ROUTE_PROGRAM_TERMINATOR: u8 = 0xc1;
pub const SOURCE_KIND4_PLAYER_SLOT_COUNT: usize = 7;
/// `FUN_00456d00` uses this remaining-motion amount when its terminal route
/// program belongs to an inactive remote or non-playable player state.
pub const SOURCE_KIND4_DEFERRED_IDLE_REMAINING: f32 = 1.0;
/// `FUN_00456d00` restores this source remaining-motion amount after its
/// ordinary terminal-program and failed-route branches.
pub const SOURCE_KIND4_TERMINAL_IDLE_REMAINING: f32 = 2.0;
/// `FUN_00456d00` pairs the terminal remaining amount with this source
/// motion rate, producing a two-second dispatch pause.
pub const SOURCE_KIND4_TERMINAL_IDLE_RATE: f32 = 0.02;

/// Locally reconstructed entity participating in the source candidate list
/// assembled by `FUN_00453da0` and consumed by
/// `FUN_0045cd20`. The source category-local slot is meaningful only with
/// its [`SourceCombatCandidate::figure_kind`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SourceCombatCandidateEntity {
    MilitaryUnit(usize),
    TradeShip(usize),
    DynamicFigure(usize),
}

/// Source-live identity and placement required by the common candidate
/// producer. This view covers every currently reconstructed entity carrying
/// a live category tag; runtime-created categories can enter by preserving
/// the same identity fields on their local representation.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct SourceCombatCandidate {
    pub entity: SourceCombatCandidateEntity,
    pub figure_kind: u8,
    pub runtime_slot: u16,
    /// Compiled `figuren.cod` definition ID loaded at runtime offset `+0x44`.
    pub figure_definition_id: Option<u16>,
    /// Live energy consumed by `FUN_00454250`'s candidate score curves.
    pub source_energy: u16,
    /// Shared category-1/2/3 slot byte `+0x1a2`. The SHIP4 loader copies
    /// raw record byte `0x42` here; `FUN_00454250` maps it to a target
    /// strength multiplier independently from the source movement direction.
    pub source_score_state: u8,
    /// Raw SHIP4 entries at `0x132 + 8i`. The loader resolves their low-16
    /// source IDs before placing the translated policy entries at `+0x1f4`.
    /// These remain raw until the executable's definition translation is
    /// reconstructed.
    pub source_kind6_policy_raw_slots: [u64; 8],
    /// Low bytes resolved by `FUN_0045f9b2` from the raw SHIP4 policy slots.
    /// `FUN_00458e60` compares these against `0x19..=0x2c`.
    pub source_kind6_policy_ware_slots: [u8; 8],
    /// Bytes at the backing category record's `+0x18/+0x19`, preserved from
    /// the static source records for consumers that read that payload. They
    /// do not identify a `FUN_00445650` figure target.
    pub source_kind6_target_descriptor_payload: Option<[u8; 2]>,
    /// Category-6 table descriptor at `+0x10`. `FUN_00444fe0` reaches this
    /// after `FUN_00445650` emits `[6, live+1, live+44]` for a category-6
    /// target. It resolves firing geometry, but is not itself the emitted
    /// action descriptor.
    pub kind6_target_descriptor: Option<SourceTargetDescriptor>,
    /// Live byte `+1`, used by `FUN_00453da0` to choose one of its candidate
    /// lists. This is independent from the faction byte at `+2`.
    pub candidate_list_key: Option<u8>,
    pub owner: u8,
    pub position: (f32, f32),
    pub direction: u8,
}

/// The two target forms consumed by `FUN_00458d80`. Ordinary candidate
/// figures resolve to a one-cell footprint at their live position. A
/// category-6 candidate redirects through its preserved table descriptor.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SourceKind6TargetGeometry {
    Point(crate::source_route::SourcePathTargetRect),
    Descriptor(SourceTargetDescriptor),
}

impl SourceCombatCandidate {
    /// Resolve the source-compiled score fields for this candidate's figure
    /// definition. Unknown definition IDs remain unavailable rather than
    /// inheriting local compatibility-unit statistics.
    pub fn combat_definition(&self) -> Option<SourceCombatDefinition> {
        self.figure_definition_id
            .and_then(SourceCombatDefinition::from_id)
    }

    /// Recover `FUN_00444fe0`'s target form for the live candidate. The
    /// executor must resolve [`SourceKind6TargetGeometry::Descriptor`] using
    /// the current source map state before calling `FUN_00458d80`'s direction
    /// gate.
    pub fn source_kind6_target_geometry(&self) -> Option<SourceKind6TargetGeometry> {
        if self.figure_kind == 6 {
            return self
                .kind6_target_descriptor
                .map(SourceKind6TargetGeometry::Descriptor);
        }

        let origin = source_kind6_action_coordinate(self.position)?;
        crate::source_route::SourcePathTargetRect::new(origin, 1, 1)
            .map(SourceKind6TargetGeometry::Point)
    }

    /// Construct the descriptor written by `FUN_00445650` into the selected
    /// category-6 score row. Every figure-table case writes its live byte
    /// `+1` followed by its little-endian live `+0x44` runtime slot.
    pub fn source_kind6_action_target_descriptor(&self) -> Option<SourceTargetDescriptor> {
        match self.figure_kind {
            1..=6 => Some(SourceTargetDescriptor::from_bytes([
                self.figure_kind,
                self.candidate_list_key?,
                self.runtime_slot as u8,
                (self.runtime_slot >> 8) as u8,
            ])),
            _ => None,
        }
    }
}

/// Resolve the figure-table cases of `FUN_00444fe0`. Kinds `1` through `5`
/// identify one live table record by its category, list key, and runtime slot;
/// kind `6` first redirects through that record's stored target descriptor.
/// The caller resolves static-map and packed-coordinate forms separately.
pub fn source_figure_target_rect(
    descriptor: SourceTargetDescriptor,
    candidates: &[SourceCombatCandidate],
    mut resolve_non_figure: impl FnMut(SourceTargetDescriptor) -> Option<SourcePathTargetRect>,
) -> Option<SourcePathTargetRect> {
    source_figure_target_rect_with_resolver(descriptor, candidates, &mut resolve_non_figure)
}

fn source_figure_target_rect_with_resolver(
    descriptor: SourceTargetDescriptor,
    candidates: &[SourceCombatCandidate],
    resolve_non_figure: &mut impl FnMut(SourceTargetDescriptor) -> Option<SourcePathTargetRect>,
) -> Option<SourcePathTargetRect> {
    match descriptor.kind() {
        1..=5 => {
            let candidate = candidates.iter().find(|candidate| {
                candidate.source_kind6_action_target_descriptor() == Some(descriptor)
            })?;
            let origin = source_figure_descriptor_coordinate(candidate.position)?;
            SourcePathTargetRect::new(origin, 1, 1)
        }
        6 => {
            let candidate = candidates.iter().find(|candidate| {
                candidate.figure_kind == 6
                    && candidate.source_kind6_action_target_descriptor() == Some(descriptor)
            })?;
            candidate
                .kind6_target_descriptor
                .and_then(|target| {
                    source_figure_target_rect_with_resolver(target, candidates, resolve_non_figure)
                })
        }
        _ => resolve_non_figure(descriptor),
    }
}

/// `FUN_00444af0` converts the live `+0x28/+0x2c` figure coordinates with
/// its x87 integer conversion before `FUN_00444fe0` supplies a one-cell
/// footprint.
fn source_figure_descriptor_coordinate(position: (f32, f32)) -> Option<(i32, i32)> {
    Some((
        source_figure_descriptor_component(position.0)?,
        source_figure_descriptor_component(position.1)?,
    ))
}

fn source_figure_descriptor_component(value: f32) -> Option<i32> {
    (value.is_finite() && value >= i32::MIN as f32 && value < i32::MAX as f32)
        .then_some(value as i32)
}

