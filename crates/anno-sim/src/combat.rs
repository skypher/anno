fn source_kind4_curve_value(index: usize, segments: &[(usize, usize, i32, i32)]) -> u8 {
    for &(start, end, start_value, end_value) in segments {
        if (start..=end).contains(&index) {
            if index == end {
                return end_value as u8;
            }
            let step = (end_value * 256 - start_value * 256) / (end - start) as i32;
            return ((start_value * 256 + step * (index - start) as i32) >> 8) as u8;
        }
    }
    0
}

/// Detect combat engagements and apply damage for one tick.
/// Returns indices of units that died this tick.
pub fn tick_combat(
    units: &mut [MilitaryUnit],
    diplomacy: &DiplomacyMatrix,
    dt_ms: u32,
) -> Vec<usize> {
    tick_combat_with_maps(units, diplomacy, dt_ms, None, &[])
}

/// Detect combat engagements and apply damage using the map route available
/// to the active simulation. Type-4 movement reaches its selected target
/// through `FUN_00453e50`'s terrain-aware grid rather than a direct line.
pub fn tick_combat_with_maps(
    units: &mut [MilitaryUnit],
    diplomacy: &DiplomacyMatrix,
    dt_ms: u32,
    ocean_map: Option<&crate::ocean_map::OceanMap>,
    island_maps: &[crate::island_map::IslandMap],
) -> Vec<usize> {
    let mut dead = Vec::new();
    let len = units.len();

    // Phase 1: Find engagement targets
    for i in 0..len {
        if !units[i].is_alive() || is_source_kind4_land_figure(&units[i]) {
            continue;
        }

        // Skip if already has a valid target
        if units[i].combat_target >= 0 {
            let target_idx = units[i].combat_target as usize;
            if target_idx < len && units[target_idx].is_alive() {
                continue; // Keep existing target
            }
            units[i].combat_target = -1; // Target died, clear it
        }

        let best = find_nearest_enemy(units, i, diplomacy, island_maps);
        units[i].combat_target = best.map(|idx| idx as i32).unwrap_or(-1);
    }

    // Phase 2: Apply damage
    for i in 0..len {
        if !units[i].is_alive() || units[i].combat_target < 0 {
            continue;
        }

        let target_idx = units[i].combat_target as usize;
        if target_idx >= len || !units[target_idx].is_alive() {
            continue;
        }

        let stats = units[i].unit_type.stats();
        let dist = unit_distance_sq(&units[i], &units[target_idx], island_maps);

        // Check if within attack range
        let range_sq = stats.attack_range * stats.attack_range;
        if dist > range_sq {
            // Source type-4 figures already advanced through their packed
            // `FUN_00457ce0` program before this compatibility damage phase.
            if is_source_kind4_land_figure(&units[i]) {
                continue;
            }
            // `FUN_00451890` consumes the dispatcher delta through each
            // active figure's state accumulator. Combat approach therefore
            // uses the same elapsed movement cadence as issued orders rather
            // than advancing once for every caller invocation.
            let speed = stats.move_speed.max(1) as u32;
            let step_ms = (1000 / speed).max(100);
            units[i].move_timer_ms = units[i].move_timer_ms.saturating_add(dt_ms);
            while units[i].move_timer_ms >= step_ms {
                let current_dist = unit_distance_sq(&units[i], &units[target_idx], island_maps);
                if current_dist <= range_sq {
                    units[i].move_timer_ms = 0;
                    break;
                }
                let target_position = (units[target_idx].tile_x, units[target_idx].tile_y);
                let Some((next_x, next_y)) =
                    next_step_to(&units[i], target_position, ocean_map, island_maps)
                else {
                    break;
                };
                let dx = next_x - units[i].tile_x;
                let dy = next_y - units[i].tile_y;
                units[i].tile_x = next_x;
                units[i].tile_y = next_y;
                units[i].direction = match (dx.signum(), dy.signum()) {
                    (0, -1) => 0,
                    (1, -1) => 1,
                    (1, 0) => 2,
                    (1, 1) => 3,
                    (0, 1) => 4,
                    (-1, 1) => 5,
                    (-1, 0) => 6,
                    (-1, -1) => 7,
                    _ => units[i].direction,
                };
                units[i].move_timer_ms -= step_ms;
            }
            continue;
        }

        // Attack timer
        units[i].attack_timer_ms += dt_ms;
        if units[i].attack_timer_ms >= stats.attack_speed_ms {
            units[i].attack_timer_ms -= stats.attack_speed_ms;

            // Apply damage to target. Naval units scale with the
            // number of cannons mounted (manual sec. 9.2.3): each
            // cannon adds 25% on top of the base hull damage. Land
            // units have cannons = 0 so they're unaffected.
            let cannons = units[i].cannons;
            let damage = stats.attack_damage * (1.0 + cannons as f32 * 0.25);
            units[target_idx].health -= damage;

            // Check if target died
            if !units[target_idx].is_alive() {
                units[target_idx].active = false;
                dead.push(target_idx);
                // Clear all references to dead unit
                for u in units.iter_mut() {
                    if u.combat_target == target_idx as i32 {
                        u.combat_target = -1;
                    }
                }
            }
        }
    }

    dead
}

