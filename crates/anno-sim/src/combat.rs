/// `FUN_0045e170` scans this shared table for categories 1, 2, 3, and 5.
pub(crate) const SOURCE_DYNAMIC_SHARED_SLOT_CAPACITY: u16 = 150;
/// `FUN_00449ca0` scans this category-4 table.
pub(crate) const SOURCE_DYNAMIC_KIND4_SLOT_CAPACITY: u16 = 400;
/// `FUN_0045e110` scans this category-6 table.
pub(crate) const SOURCE_DYNAMIC_KIND6_SLOT_CAPACITY: u16 = 350;

/// Return the source dynamic-figure table identity and its capacity for a
/// source category. `FUN_0045d380` selects these three tables: categories
/// 1/2/3/5 share `0x218`-byte records, category 4 uses `0x1b0`-byte records,
/// and category 6 uses `0x118`-byte records.
pub(crate) fn source_dynamic_slot_table(figure_kind: u8) -> Option<(u8, u16)> {
    match figure_kind {
        1 | 2 | 3 | 5 => Some((0, SOURCE_DYNAMIC_SHARED_SLOT_CAPACITY)),
        4 => Some((1, SOURCE_DYNAMIC_KIND4_SLOT_CAPACITY)),
        6 => Some((2, SOURCE_DYNAMIC_KIND6_SLOT_CAPACITY)),
        _ => None,
    }
}

/// Construct the locally available portion of `FUN_0045cd20`'s candidate
/// population. Static SHIP4 records supply categories 1 and 3, while
/// SOLDAT3 supplies category 4. The source only accepts tags 1 through 6;
/// malformed or non-source entities are excluded here before pair scoring.
/// Runtime-created category records retain their candidate-list key directly
/// from the `0x84a` spawn payload.
pub fn source_combat_candidate_buffer(
    units: &[MilitaryUnit],
    trade_ships: &[crate::trade::TradeShip],
    dynamic_figures: &[SourceDynamicCombatFigure],
) -> Vec<SourceCombatCandidate> {
    let mut candidates = Vec::new();
    for (index, unit) in units.iter().enumerate() {
        let (Some(figure_kind), Some(runtime_slot)) =
            (unit.source_figure_kind, unit.source_live_runtime_slot)
        else {
            continue;
        };
        if !unit.active || !(1..=6).contains(&figure_kind) {
            continue;
        }
        let position = if unit.source_position_initialized {
            (unit.source_position_x, unit.source_position_y)
        } else {
            (unit.tile_x as f32, unit.tile_y as f32)
        };
        candidates.push(SourceCombatCandidate {
            entity: SourceCombatCandidateEntity::MilitaryUnit(index),
            figure_kind,
            runtime_slot,
            figure_definition_id: unit.source_figure_definition_id,
            source_energy: unit.source_energy,
            source_score_state: unit.source_score_state,
            source_kind6_policy_raw_slots: unit.source_kind6_policy_raw_slots,
            source_kind6_policy_ware_slots: unit.source_kind6_policy_ware_slots,
            source_kind6_target_descriptor_payload: unit.source_kind6_target_descriptor_payload,
            kind6_target_descriptor: None,
            candidate_list_key: unit.source_candidate_list_key,
            owner: unit.owner,
            position,
            direction: unit.direction,
        });
    }
    for (index, ship) in trade_ships.iter().enumerate() {
        let (Some(figure_kind), Some(runtime_slot)) =
            (ship.source_figure_kind, ship.source_runtime_slot)
        else {
            continue;
        };
        if !ship.active || !(1..=6).contains(&figure_kind) {
            continue;
        }
        candidates.push(SourceCombatCandidate {
            entity: SourceCombatCandidateEntity::TradeShip(index),
            figure_kind,
            runtime_slot,
            figure_definition_id: ship.source_figure_definition_id,
            source_energy: ship.source_energy,
            source_score_state: ship.source_score_state,
            source_kind6_policy_raw_slots: ship.source_kind6_policy_raw_slots,
            source_kind6_policy_ware_slots: ship.source_kind6_policy_ware_slots,
            source_kind6_target_descriptor_payload: ship.source_kind6_target_descriptor_payload,
            kind6_target_descriptor: None,
            candidate_list_key: ship.source_candidate_list_key,
            owner: ship.owner,
            position: (ship.world_x as f32, ship.world_y as f32),
            direction: ship.source_direction,
        });
    }
    for (index, figure) in dynamic_figures.iter().enumerate() {
        if !figure.active || !(1..=6).contains(&figure.figure_kind) {
            continue;
        }
        candidates.push(SourceCombatCandidate {
            entity: SourceCombatCandidateEntity::DynamicFigure(index),
            figure_kind: figure.figure_kind,
            runtime_slot: figure.runtime_slot,
            figure_definition_id: Some(u16::from(figure.figure_definition_id)),
            source_energy: figure.source_energy,
            source_score_state: 0,
            source_kind6_policy_raw_slots: [0; 8],
            source_kind6_policy_ware_slots: [0; 8],
            source_kind6_target_descriptor_payload: None,
            kind6_target_descriptor: (figure.figure_kind == 6).then_some(figure.target_descriptor),
            candidate_list_key: Some(figure.candidate_list_key),
            owner: figure.owner,
            position: figure.position,
            direction: figure.direction,
        });
    }
    candidates
}

/// Reconstruct the directed rows that `FUN_0045cd20` writes for one source
/// figure. Its position fields are continuous runtime coordinates; the
/// executable truncates each coordinate after multiplying by eight before
/// the spatial sort and pair metric. The sign of the source y conversion is
/// immaterial to pair differences, so this retains its magnitude only.
pub fn source_combat_candidate_pairs(
    attacker: &SourceCombatCandidate,
    candidates: &[SourceCombatCandidate],
    diplomacy: &DiplomacyMatrix,
) -> Vec<SourceCombatCandidatePair> {
    let Some(candidate_list_key) = attacker.candidate_list_key else {
        return Vec::new();
    };
    let Some(attacker_position) = source_combat_candidate_pair_coordinates(attacker) else {
        return Vec::new();
    };

    let mut pairs = candidates
        .iter()
        .copied()
        .enumerate()
        .filter_map(|(source_order, target)| {
            if target.entity == attacker.entity
                || target.candidate_list_key != Some(candidate_list_key)
                || target.owner == attacker.owner
                || diplomacy.get(attacker.owner, target.owner) == Diplomacy::Allied
                || ((1..=3).contains(&attacker.figure_kind)
                    && (1..=3).contains(&target.figure_kind))
            {
                return None;
            }

            let target_position = source_combat_candidate_pair_coordinates(&target)?;
            let dx = attacker_position.0.abs_diff(target_position.0);
            let dy = attacker_position.1.abs_diff(target_position.1);
            if dx > SOURCE_COMBAT_CANDIDATE_AXIS_LIMIT
                || dy > SOURCE_COMBAT_CANDIDATE_AXIS_LIMIT
            {
                return None;
            }

            let metric = dx.max(dy) + dx.min(dy) / 4;
            u16::try_from(metric).ok().map(|metric| {
                (
                    target_position.0,
                    source_order,
                    SourceCombatCandidatePair { target, metric },
                )
            })
        })
        .collect::<Vec<_>>();
    // `FUN_00452190` orders each candidate-list population by the transformed
    // x coordinate before `FUN_0045cd20` appends directed rows. Preserve the
    // input order for an equal coordinate, matching the source list order.
    pairs.sort_by_key(|(x, source_order, _)| (*x, *source_order));
    pairs.truncate(SOURCE_COMBAT_CANDIDATE_CAPACITY);
    pairs.into_iter().map(|(_, _, pair)| pair).collect()
}

fn source_combat_candidate_pair_coordinates(
    candidate: &SourceCombatCandidate,
) -> Option<(i32, i32)> {
    Some((
        source_combat_pair_coordinate(candidate.position.0)?,
        source_combat_pair_coordinate(candidate.position.1)?,
    ))
}

fn source_kind6_action_coordinate(position: (f32, f32)) -> Option<(i32, i32)> {
    Some((
        source_kind6_action_component(position.0)?,
        source_kind6_action_component(position.1)?,
    ))
}

fn source_kind6_action_component(value: f32) -> Option<i32> {
    let scaled = value * 2.0;
    (scaled.is_finite() && scaled >= i32::MIN as f32 && scaled < i32::MAX as f32)
        .then_some(scaled as i32)
}

fn source_combat_pair_coordinate(value: f32) -> Option<i32> {
    let scaled = value * 8.0;
    (scaled.is_finite() && scaled >= i32::MIN as f32 && scaled < i32::MAX as f32)
        .then_some(scaled as i32)
}

/// Source player globals read by `FUN_00456d00` before it decides whether a
/// terminal type-4 program may construct another route. `active_player_slot`
/// models `DAT_005bacb0`; `single_player` models the flag initialized from
/// `DAT_005bafdc < 2`; `faction_states` preserves `PLAYER4 + 4` values.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct SourceKind4DispatchState {
    pub active_player_slot: u8,
    pub single_player: bool,
    pub faction_states: [u8; SOURCE_KIND4_PLAYER_SLOT_COUNT],
}

impl Default for SourceKind4DispatchState {
    fn default() -> Self {
        Self {
            active_player_slot: 0,
            single_player: true,
            faction_states: [0, 0x0c, 0x0c, 0x0c, 0x0d, 0x0e, 0x0b],
        }
    }
}

impl SourceKind4DispatchState {
    /// Construct the source dispatch globals from the raw `PLAYER4 + 4`
    /// faction bytes. The source's current local player is the configured
    /// human slot (`0`), falling back to slot zero for malformed records.
    pub fn from_player4_faction_states(
        faction_states: [u8; SOURCE_KIND4_PLAYER_SLOT_COUNT],
    ) -> Self {
        let active_player_slot = faction_states
            .iter()
            .position(|&state| state == 0)
            .unwrap_or(0) as u8;
        Self {
            active_player_slot,
            single_player: true,
            faction_states,
        }
    }

    /// `FUN_00456d00`'s early terminal-program condition. In a multiplayer
    /// session every non-local owner defers; in single-player it defers only
    /// for a source player state outside the active `0x0b..=0x0e` range.
    pub fn defers_terminal_program(self, owner: u8) -> bool {
        owner != self.active_player_slot
            && (!self.single_player
                || !self
                    .faction_states
                    .get(usize::from(owner))
                    .is_some_and(|state| (0x0b..=0x0e).contains(state)))
    }
}

