fn source_diplomacy_curve(age: u8, segments: &[(u8, u8, u8, u8)]) -> i32 {
    for &(start, end, initial, terminal) in segments {
        if age < start || age > end {
            continue;
        }
        if age == end {
            return i32::from(terminal);
        }
        let span = i32::from(end) - i32::from(start);
        let increment = (i32::from(terminal) * 0x100 - i32::from(initial) * 0x100) / span;
        return (i32::from(initial) * 0x100 + (i32::from(age) - i32::from(start)) * increment) >> 8;
    }
    0
}

fn source_diplomacy_population_curve(index: u8) -> i32 {
    source_diplomacy_curve(
        index,
        &[
            (0, 1, 0xfe, 0xd5),
            (1, 4, 0xd5, 0x80),
            (4, 8, 0x80, 0x60),
            (8, 0x0c, 0x60, 0x40),
            (0x0c, 0x14, 0x40, 0x33),
            (0x14, 0x28, 0x33, 0x26),
            (0x28, 0x46, 0x26, 0x19),
            (0x46, 0x7f, 0x19, 0x0c),
        ],
    )
}

fn source_diplomacy_own_population_penalty(index: u8) -> i32 {
    source_diplomacy_curve(
        index,
        &[(0, 0x40, 0xaa, 0x82), (0x40, 0x66, 0x82, 0x50), (0x66, 0x80, 0x50, 0)],
    )
}

fn source_diplomacy_peer_population_penalty(index: u8) -> i32 {
    source_diplomacy_curve(
        index,
        &[(0, 0x19, 0, 0x46), (0x19, 0x40, 0x46, 0x82), (0x40, 0x80, 0x82, 0xaa)],
    )
}

fn source_diplomacy_city_strength_penalty(index: u8) -> i32 {
    source_diplomacy_curve(
        index,
        &[(0, 0x19, 0, 0x46), (0x19, 0x2a, 0x46, 0x82), (0x2a, 0x80, 0x82, 0xaa)],
    )
}

fn source_signed_fixed_div_4096(value: i32) -> i32 {
    value.wrapping_add((value >> 31) & 0x0fff) >> 12
}

/// Replays `FUN_00475fe0` for one queued record. The source forms the age by
/// unsigned subtraction before shifting, so a future timestamp saturates at
/// the same 255 bucket as an old timestamp after wraparound.
pub fn source_diplomacy_event_age_score(
    event: SourceDiplomacyEvent,
    source_time_ticks: u32,
) -> i32 {
    if event.event_type == 0 {
        return 0;
    }
    let age = ((source_time_ticks.wrapping_sub(event.timestamp) >> 7).min(0xff)) as u8;
    let magnitude = match event.event_type {
        1 => source_diplomacy_curve(
            age,
            &[
                (0, 0x32, 0x1e, 0x12),
                (0x32, 0x4b, 0x12, 0),
                (0x4b, 0xff, 0, 0),
            ],
        ),
        3 => source_diplomacy_curve(
            age,
            &[
                (0, 0x4b, 0x1e, 0x12),
                (0x4b, 0x96, 0x12, 8),
                (0x96, 200, 8, 0),
                (200, 0xff, 0, 0),
            ],
        ),
        5 => source_diplomacy_curve(
            age,
            &[
                (0, 0x32, 0x32, 0x19),
                (0x32, 0x4b, 0x19, 0),
                (0x4b, 0xff, 0, 0),
            ],
        ),
        6 => source_diplomacy_curve(
            age,
            &[(0, 0x1e, 0x0c, 7), (0x1e, 0x32, 7, 0), (0x32, 0xff, 0, 0)],
        ),
        7 => source_diplomacy_curve(
            age,
            &[
                (0, 100, 0x46, 0x23),
                (100, 0xfa, 0x23, 0),
                (0xfa, 0xff, 0, 0),
            ],
        ),
        8 => -source_diplomacy_curve(
            age,
            &[
                (0, 0x50, 0x3c, 0x1e),
                (0x50, 200, 0x1e, 0),
                (200, 0xff, 0, 0),
            ],
        ),
        9 => source_diplomacy_curve(
            age,
            &[
                (0, 0x1e, 0x19, 0x0d),
                (0x1e, 0x2d, 0x0d, 0),
                (0x2d, 0xff, 0, 0),
            ],
        ),
        10 => -source_diplomacy_curve(
            age,
            &[
                (0, 0x32, 100, 0x32),
                (0x32, 0x46, 0x32, 10),
                (0x46, 100, 10, 0),
                (100, 0xff, 0, 0),
            ],
        ),
        11 => source_diplomacy_curve(
            age,
            &[
                (0, 0x50, 0x28, 0x14),
                (0x50, 200, 0x14, 0),
                (200, 0xff, 0, 0),
            ],
        ),
        12 => source_diplomacy_curve(
            age,
            &[
                (0, 0x50, 0x1e, 0x0f),
                (0x50, 200, 0x0f, 0),
                (200, 0xff, 0, 0),
            ],
        ),
        13 => -source_diplomacy_curve(
            age,
            &[
                (0, 0x50, 0x1e, 0x0f),
                (0x50, 200, 0x0f, 0),
                (200, 0xff, 0, 0),
            ],
        ),
        _ => 0,
    };
    magnitude
}

impl DiplomacyMatrix {
    pub fn new() -> Self {
        let mut relations = [[Diplomacy::Neutral; 7]; 7];
        // Self is always allied
        for i in 0..7 {
            relations[i][i] = Diplomacy::Allied;
        }
        Self {
            relations,
            source_relation_codes: default_source_relation_codes(),
            source_attitude_codes: default_source_attitude_codes(),
            source_diplomacy_event_queues: default_source_diplomacy_event_queues(),
            source_diplomacy_activity: default_source_diplomacy_activity(),
            source_diplomacy_pair_base: default_source_diplomacy_pair_weights(),
            source_diplomacy_pair_scale: default_source_diplomacy_pair_weights(),
            source_diplomacy_policy_flags: default_source_diplomacy_policy_flags(),
            source_diplomacy_peer_population_threshold: default_source_diplomacy_policy_u16(),
            source_diplomacy_own_population_threshold: default_source_diplomacy_policy_u16(),
            source_diplomacy_own_city_strength: default_source_diplomacy_policy_u8(),
            source_diplomacy_peer_city_strength: default_source_diplomacy_policy_u8(),
            source_diplomacy_player_states: default_source_diplomacy_player_states(),
            source_diplomacy_queue_state: default_source_diplomacy_queue_state(),
            trade_agreement: [[false; 7]; 7],
            trade_agreement_broken: [[false; 7]; 7],
        }
    }

    pub fn new_all_war() -> Self {
        let mut dm = Self::new();
        for i in 0..7 {
            for j in 0..7 {
                if i != j {
                    dm.relations[i][j] = Diplomacy::War;
                    dm.source_relation_codes[i][j] = 0;
                }
            }
        }
        dm
    }

    pub fn get(&self, a: u8, b: u8) -> Diplomacy {
        if a as usize >= 7 || b as usize >= 7 {
            return Diplomacy::Neutral;
        }
        self.relations[a as usize][b as usize]
    }

    pub fn set(&mut self, a: u8, b: u8, state: Diplomacy) {
        if a as usize >= 7 || b as usize >= 7 {
            return;
        }
        self.relations[a as usize][b as usize] = state;
        self.relations[b as usize][a as usize] = state;
        let source_code = match state {
            Diplomacy::Allied => 3,
            Diplomacy::Neutral | Diplomacy::War => 0,
        };
        self.source_relation_codes[a as usize][b as usize] = source_code;
        self.source_relation_codes[b as usize][a as usize] = source_code;
        // Manual sec. 7.2: declaring war breaks any trade agreement.
        if state == Diplomacy::War {
            self.trade_agreement[a as usize][b as usize] = false;
            self.trade_agreement[b as usize][a as usize] = false;
        }
    }

    /// Preserve one directed `DAT_005b7770` relationship code. The source
    /// candidate producer uses only code `3` as its non-combat exclusion; the
    /// compatibility matrix mirrors that boundary without discarding raw
    /// codes `0` through `2`.
    pub fn set_source_relationship_code(&mut self, attacker: u8, target: u8, code: u32) {
        if attacker as usize >= 7 || target as usize >= 7 {
            return;
        }
        self.source_relation_codes[attacker as usize][target as usize] = code;
        self.relations[attacker as usize][target as usize] = if attacker == target || code == 3 {
            Diplomacy::Allied
        } else {
            Diplomacy::Neutral
        };
    }

    /// Return the directed source relation byte preserved from PLAYER4.
    pub fn source_relationship_code(&self, attacker: u8, target: u8) -> u32 {
        self.source_relation_codes
            .get(attacker as usize)
            .and_then(|row| row.get(target as usize))
            .copied()
            .unwrap_or(0)
    }

    /// `FUN_0045cd20` admits a directed target exactly when this predicate is
    /// false: only source relationship code `3` suppresses the combat row.
    pub fn source_relationship_excludes_combat(&self, attacker: u8, target: u8) -> bool {
        self.source_relationship_code(attacker, target) == 3
    }

    /// Return the directed source attitude byte at `DAT_005b77b0`.
    pub fn source_attitude_code(&self, source: u8, target: u8) -> u8 {
        self.source_attitude_codes
            .get(source as usize)
            .and_then(|row| row.get(target as usize))
            .copied()
            .unwrap_or(0)
    }

    /// Preserve one directed `DAT_005b77b0` attitude byte from PLAYER4.
    /// Scenario loading copies this table directly and does not apply the
    /// reciprocal update rules of a later `0x30` event.
    pub fn set_source_attitude_code(&mut self, source: u8, target: u8, code: u8) {
        if source as usize >= 7 || target as usize >= 7 {
            return;
        }
        self.source_attitude_codes[source as usize][target as usize] = code;
    }

    /// Execute the directed `FUN_004760e0` / `0x2f` relation transition.
    /// The constructor compares `DAT_005b7770` directly against the raw
    /// payload before it allocates event `0x2f`. Payload 1 therefore remains
    /// repeatable after its handler stores code 2; only payloads 0 and 3
    /// become duplicate-suppressed by their resulting source byte.
    pub fn apply_source_relationship_event(
        &mut self,
        source: u8,
        target: u8,
        event: SourceRelationshipEvent,
    ) -> bool {
        if source as usize >= 7 || target as usize >= 7 {
            return false;
        }
        if self.source_relationship_code(source, target) == event as u8 as u32 {
            return false;
        }
        self.set_source_relationship_code(source, target, event.relationship_code());
        true
    }

    /// Decode and execute the raw `FUN_004760e0` event payload. Values other
    /// than `0`, `1`, and `3` are not constructed by that source function.
    pub fn apply_source_relationship_payload(
        &mut self,
        source: u8,
        target: u8,
        payload: u8,
    ) -> bool {
        match SourceRelationshipEvent::from_payload(payload) {
            Some(event) => self.apply_source_relationship_event(source, target, event),
            None => false,
        }
    }

    /// Execute the directed `FUN_00476130` / `0x30` attitude transition.
    /// The source constructor submits only payloads `0`, `1`, and `3`, and
    /// suppresses the event if the source-to-target byte already equals that
    /// payload. The `0x30` handler writes reciprocal bytes `0/0`, `1/2`, or
    /// `3/3`, respectively.
    pub fn apply_source_attitude_payload(&mut self, source: u8, target: u8, payload: u8) -> bool {
        if source as usize >= 7 || target as usize >= 7 {
            return false;
        }
        if !matches!(payload, 0 | 1 | 3) || self.source_attitude_code(source, target) == payload {
            return false;
        }

        let (forward, reverse) = match payload {
            0 => (0, 0),
            1 => (1, 2),
            3 => (3, 3),
            _ => return false,
        };
        self.source_attitude_codes[source as usize][target as usize] = forward;
        self.source_attitude_codes[target as usize][source as usize] = reverse;
        true
    }

    /// Return one player's fixed 32-slot `DAT_005b77f0` notification queue.
    pub fn source_diplomacy_event_queue(
        &self,
        player: u8,
    ) -> Option<&[SourceDiplomacyEvent; SOURCE_DIPLOMACY_EVENT_QUEUE_CAPACITY]> {
        self.source_diplomacy_event_queues.get(player as usize)
    }

    /// Return the directed `DAT_005b7750` activity counter maintained by
    /// `FUN_00477390`.
    pub fn source_diplomacy_activity(&self, player: u8, peer: u8) -> u32 {
        self.source_diplomacy_activity
            .get(player as usize)
            .and_then(|row| row.get(peer as usize))
            .copied()
            .unwrap_or(0)
    }

    /// Preserve the three directed inputs read by `FUN_00475c60` from one
    /// PLAYER4 row: `DAT_005b7750`, `DAT_005b7730`, and `DAT_005b7740`.
    pub fn set_source_diplomacy_score_inputs(
        &mut self,
        player: u8,
        peer: u8,
        activity: u32,
        base: u16,
        scale: u16,
    ) {
        if player as usize >= 7 || peer as usize >= 7 {
            return;
        }
        self.source_diplomacy_activity[player as usize][peer as usize] = activity;
        self.source_diplomacy_pair_base[player as usize][peer as usize] = base;
        self.source_diplomacy_pair_scale[player as usize][peer as usize] = scale;
    }

    /// Return the directed `DAT_005b7730` / `DAT_005b7740` score inputs.
    pub fn source_diplomacy_pair_weights(&self, player: u8, peer: u8) -> (u16, u16) {
        if player as usize >= 7 || peer as usize >= 7 {
            return (0, 0);
        }
        (
            self.source_diplomacy_pair_base[player as usize][peer as usize],
            self.source_diplomacy_pair_scale[player as usize][peer as usize],
        )
    }

    /// Preserve the PLAYER4 controls that select the policy deductions in
    /// `FUN_00475c60`, together with the source runtime player-state byte.
    pub fn set_source_diplomacy_policy_inputs(
        &mut self,
        player: u8,
        player_state: u8,
        flags: u32,
        peer_population_threshold: u16,
        own_population_threshold: u16,
        own_city_strength: u8,
        peer_city_strength: u8,
    ) {
        let index = player as usize;
        if index >= 7 {
            return;
        }
        self.source_diplomacy_player_states[index] = player_state;
        self.source_diplomacy_policy_flags[index] = flags;
        self.source_diplomacy_peer_population_threshold[index] = peer_population_threshold;
        self.source_diplomacy_own_population_threshold[index] = own_population_threshold;
        self.source_diplomacy_own_city_strength[index] = own_city_strength;
        self.source_diplomacy_peer_city_strength[index] = peer_city_strength;
    }

    /// Full `FUN_00475c60` score. `island_runtime_classification` supplies the
    /// island-record u16 at `+0x18` so this map-independent score kernel can
    /// be used without depending on simulation storage.
    pub fn source_diplomacy_score(
        &self,
        player: u8,
        peer: u8,
        caller_term: i32,
        source_time_ticks: u32,
        cities: &[SourceDiplomacyCity],
        kind4_occupants: &[SourceDiplomacyKind4Occupant],
        dynamic_objects: &[SourceDiplomacyDynamicObject],
        island_runtime_classification: impl Fn(u8) -> u16,
    ) -> i32 {
        let (player_index, peer_index) = (player as usize, peer as usize);
        if player_index >= 7 || peer_index >= 7 {
            return 0;
        }

        let mut player_residents = 0_u32;
        let mut peer_residents = 0_u32;
        let mut player_city_strength = 0_i32;
        let mut peer_city_strength = 0_i32;
        let player_city_count = cities
            .iter()
            .filter(|city| city.owner_slot == player)
            .count();
        let mut island_presence_penalty = 0_i32;
        let mut map_object_penalty = 0_i32;

        for city in cities {
            if city.owner_slot == player {
                if matches!(self.source_diplomacy_player_states[player_index], 0x0c | 0x0e) {
                    let peer_has_object = dynamic_objects
                        .iter()
                        .any(|object| object.island_id == city.island_id && object.owner == peer);
                    if peer_has_object {
                        if island_runtime_classification(city.island_id) < 4
                            && (player_city_count < 3 || city.tier_population_total() != 0)
                        {
                            map_object_penalty = 200;
                        }
                    }

                    let peer_presence = kind4_occupants.iter().any(|occupant| {
                        occupant.island_id == city.island_id && occupant.owner == peer
                    });
                    if peer_presence {
                        let player_presence = kind4_occupants.iter().any(|occupant| {
                            occupant.island_id == city.island_id && occupant.owner == player
                        });
                        island_presence_penalty = island_presence_penalty.max(if player_presence
                            && peer_has_object
                        {
                            60
                        } else {
                            200
                        });
                    }
                }

                let residents = city.resident_total();
                player_residents = player_residents.wrapping_add(residents);
                if self.source_diplomacy_policy_flags[player_index] & 0x100 != 0 {
                    player_city_strength = player_city_strength.max(city.strength());
                }
            } else if city.owner_slot == peer {
                let residents = city.resident_total();
                peer_residents = peer_residents.wrapping_add(residents);
                if self.source_diplomacy_policy_flags[player_index] & 0x200 != 0 {
                    peer_city_strength = peer_city_strength.max(city.strength());
                }
            }
        }

        let mut policy_penalty = island_presence_penalty + map_object_penalty;
        let flags = self.source_diplomacy_policy_flags[player_index];
        if flags & 0x10 != 0
            && peer_residents
                > u32::from(self.source_diplomacy_peer_population_threshold[player_index])
            && self.source_diplomacy_player_states[peer_index] == 0
        {
            // The executable computes the quotient, then assigns 0x80 unless
            // it already equals 0x80. Every defined input therefore indexes
            // the terminal point of DAT_00548fc0.
            policy_penalty += source_diplomacy_peer_population_penalty(0x80);
        }
        if flags & 0x80 != 0
            && player_residents
                <= u32::from(self.source_diplomacy_own_population_threshold[player_index])
            && self.source_diplomacy_player_states[peer_index] == 0
        {
            let threshold = u32::from(self.source_diplomacy_own_population_threshold[player_index]);
            if threshold != 0 {
                policy_penalty += source_diplomacy_own_population_penalty(
                    (player_residents.wrapping_shl(7) / threshold) as u8,
                );
            }
        }
        if flags & 0x200 != 0
            && peer_city_strength
                > i32::from(self.source_diplomacy_peer_city_strength[player_index])
            && self.source_diplomacy_player_states[peer_index] == 0
        {
            policy_penalty += source_diplomacy_city_strength_penalty(
                (peer_city_strength - i32::from(self.source_diplomacy_peer_city_strength[player_index]))
                    as u8,
            );
        }
        if flags & 0x100 != 0
            && player_city_strength
                < i32::from(self.source_diplomacy_own_city_strength[player_index])
        {
            policy_penalty += source_diplomacy_city_strength_penalty(
                (i32::from(self.source_diplomacy_own_city_strength[player_index]) - player_city_strength)
                    as u8,
            );
        }

        self.source_diplomacy_score_without_policy(
            player,
            peer,
            caller_term,
            player_residents,
            peer_residents,
            source_time_ticks,
        ) - policy_penalty
    }

    /// Return the player byte at offset `+0x83` that source queue insertion
    /// sets to 6.
    pub fn source_diplomacy_queue_state(&self, player: u8) -> u8 {
        self.source_diplomacy_queue_state
            .get(player as usize)
            .copied()
            .unwrap_or(0)
    }

    /// The queue and activity contribution at the head of
    /// `FUN_00475c60(player, peer, param_3)`, before that routine adds the
    /// city, settlement, and caller-supplied terms.
    pub fn source_diplomacy_queue_score(
        &self,
        player: u8,
        peer: u8,
        source_time_ticks: u32,
    ) -> i32 {
        let Some(queue) = self.source_diplomacy_event_queue(player) else {
            return 0;
        };
        if peer as usize >= 7 {
            return 0;
        }
        let notification_score = queue
            .iter()
            .filter(|event| event.event_type != 0 && event.peer == peer)
            .map(|event| source_diplomacy_event_age_score(*event, source_time_ticks))
            .sum::<i32>();
        let activity_penalty =
            (self.source_diplomacy_activity[player as usize][peer as usize].wrapping_shl(3) >> 5)
                .min(100) as i32;
        notification_score - activity_penalty
    }

    /// The score portion at the tail of `FUN_00475c60` that is determined by
    /// the notification queue, `FUN_0047f790` owner totals, and PLAYER4
    /// `DAT_005b7730`/`DAT_005b7740` rows. The source's preceding policy and
    /// island-occupancy modifiers are intentionally excluded from this named
    /// component.
    pub fn source_diplomacy_score_without_policy(
        &self,
        player: u8,
        peer: u8,
        caller_term: i32,
        player_residents: u32,
        peer_residents: u32,
        source_time_ticks: u32,
    ) -> i32 {
        if player as usize >= 7 || peer as usize >= 7 {
            return 0;
        }
        let population_mix = (player_residents as i64 * 0x33 + peer_residents as i64 * 0x4c)
            .div_euclid(0x4000)
            .min(0x7f) as u8;
        let curve = source_diplomacy_population_curve(population_mix);
        let (base, scale) = self.source_diplomacy_pair_weights(player, peer);
        let base_term = source_signed_fixed_div_4096(
            (i32::from(base).wrapping_add(caller_term)).wrapping_mul(curve),
        )
        .min(0x6e);
        let scale_term = ((u32::from(scale) * curve as u32) >> 12).min(0x46) as i32;
        self.source_diplomacy_queue_score(player, peer, source_time_ticks) + base_term + scale_term
    }

    fn clear_source_diplomacy_events(&mut self, player: usize, peer: u8, event_type: u8) {
        for event in &mut self.source_diplomacy_event_queues[player] {
            if event.event_type == event_type && event.peer == peer {
                event.event_type = 0;
            }
        }
    }

    /// Replay `FUN_00477390` against a player's 32-entry notification array.
    /// The source chooses a same-type/peer entry for duplicate classes, or
    /// otherwise overwrites the entry having the smallest absolute
    /// `FUN_00475fe0` score. A non-duplicate insertion stops at the first
    /// zero-score entry, which gives empty slots first priority.
    pub fn enqueue_source_diplomacy_event(
        &mut self,
        player: u8,
        peer: u8,
        event_type: u8,
        source_time_ticks: u32,
    ) -> bool {
        let player = player as usize;
        let peer_index = peer as usize;
        if player >= 7 || peer_index >= 7 {
            return false;
        }

        let duplicate_class = match event_type {
            6 => {
                self.source_diplomacy_activity[player][peer_index] >>= 3;
                true
            }
            7 | 11 => {
                self.clear_source_diplomacy_events(player, peer, 8);
                self.source_diplomacy_activity[player][peer_index] = 0;
                true
            }
            8 => {
                self.clear_source_diplomacy_events(player, peer, 7);
                self.clear_source_diplomacy_events(player, peer, 11);
                true
            }
            9 | 10 => true,
            _ => false,
        };

        let queue = &mut self.source_diplomacy_event_queues[player];
        let mut selected = None;
        let mut best_absolute_score = i32::MAX;
        for (index, event) in queue.iter().copied().enumerate() {
            if duplicate_class && event.event_type == event_type && event.peer == peer {
                selected = Some(index);
                break;
            }

            let absolute_score = source_diplomacy_event_age_score(event, source_time_ticks).abs();
            if absolute_score < best_absolute_score {
                selected = Some(index);
                best_absolute_score = absolute_score;
                if !duplicate_class && absolute_score == 0 {
                    break;
                }
            }
        }

        let Some(index) = selected else {
            return false;
        };
        queue[index] = SourceDiplomacyEvent {
            event_type,
            peer,
            timestamp: source_time_ticks,
        };
        self.source_diplomacy_queue_state[player] = 6;
        true
    }

    /// Returns true if `a` and `b` have a concluded trade agreement.
    pub fn has_trade_agreement(&self, a: u8, b: u8) -> bool {
        if a as usize >= 7 || b as usize >= 7 {
            return false;
        }
        self.trade_agreement[a as usize][b as usize]
    }

    /// Open a trade agreement between `a` and `b`. Manual sec. 7.2:
    /// rejected if either side recently broke an agreement (penalty
    /// flag set) OR if the players are at war. Sets the flag
    /// symmetrically. Returns true on success.
    pub fn propose_trade_agreement(&mut self, a: u8, b: u8) -> bool {
        if a as usize >= 7 || b as usize >= 7 || a == b {
            return false;
        }
        if self.get(a, b) == Diplomacy::War {
            return false;
        }
        if self.trade_agreement_broken[a as usize][b as usize] {
            return false;
        }
        self.trade_agreement[a as usize][b as usize] = true;
        self.trade_agreement[b as usize][a as usize] = true;
        true
    }

    /// Cancel a trade agreement. Sets the per-pair broken-flag so the
    /// next proposal is auto-rejected (manual: "seldom possible to
    /// conclude a new trade agreement right after one has been
    /// broken").
    pub fn break_trade_agreement(&mut self, a: u8, b: u8) -> bool {
        if a as usize >= 7 || b as usize >= 7 || a == b {
            return false;
        }
        if !self.trade_agreement[a as usize][b as usize] {
            return false;
        }
        self.trade_agreement[a as usize][b as usize] = false;
        self.trade_agreement[b as usize][a as usize] = false;
        self.trade_agreement_broken[a as usize][b as usize] = true;
        self.trade_agreement_broken[b as usize][a as usize] = true;
        true
    }

    /// Clear the broken-trade-agreement penalty between `a` and `b`
    /// (e.g. after enough cooldown ticks). Restores the ability to
    /// re-propose.
    pub fn clear_broken_flag(&mut self, a: u8, b: u8) {
        if a as usize >= 7 || b as usize >= 7 {
            return;
        }
        self.trade_agreement_broken[a as usize][b as usize] = false;
        self.trade_agreement_broken[b as usize][a as usize] = false;
    }
}

/// Tile distance squared between two positions.
fn distance_sq(ax: i32, ay: i32, bx: i32, by: i32) -> u32 {
    let dx = (ax - bx).unsigned_abs();
    let dy = (ay - by).unsigned_abs();
    dx * dx + dy * dy
}

/// True for the land figures backed by a `SOLDAT3` type-4 runtime slot.
/// `FUN_0045cd20` and `FUN_00456d00` operate on this set, distinct from the
/// compatibility combat mover used by ordinary and naval units.
fn is_source_kind4_land_figure(unit: &MilitaryUnit) -> bool {
    unit.source_island_id.is_some()
        && unit.source_runtime_slot.is_some()
        && unit.source_figure_definition_id.is_some()
}

/// Rebuild the source type-4 candidate relationship before its movement
/// dispatch. `FUN_00451890` calls `FUN_0045cd20` immediately before it
/// invokes `FUN_00456d00`: pairs are co-island, active, differently owned,
/// non-allied, and lie in a raw `0x60 × 0x60` neighborhood. `FUN_00456d00`
/// only ranks candidates after the current route program reaches its terminal
/// opcode; it retains candidates inside the attacker's `Shotradius + 0x40`
/// envelope and ranks them with `FUN_00454250`'s generated score curves.
/// This score-only entry point is retained for map-free callers; simulation
/// dispatch uses [`acquire_source_kind4_candidates_with_terrain`].
pub fn acquire_source_kind4_candidates(
    units: &mut [MilitaryUnit],
    diplomacy: &DiplomacyMatrix,
) {
    acquire_source_kind4_candidates_with_terrain(units, diplomacy, &[]);
}

/// Select source type-4 candidates with `FUN_00453e50`'s terminal static-map
/// direct-ray fallback. Candidate scores are ordered first; each rejected
/// `0x0d` ray advances to the next score-ranked candidate.
pub fn acquire_source_kind4_candidates_with_terrain(
    units: &mut [MilitaryUnit],
    diplomacy: &DiplomacyMatrix,
    island_maps: &[crate::island_map::IslandMap],
) {
    for unit_index in 0..units.len() {
        if !units[unit_index].is_alive()
            || !is_source_kind4_land_figure(&units[unit_index])
            || units[unit_index].source_target_descriptor.is_some()
        {
            continue;
        }

        let source_island = units[unit_index].source_island_id;
        let source_owner = units[unit_index].owner;
        let source_position = (units[unit_index].tile_x, units[unit_index].tile_y);
        let existing_target = usize::try_from(units[unit_index].combat_target).ok();
        let selected = if source_kind4_program_is_terminal(&units[unit_index]) {
            {
                let attacker = &units[unit_index];
                let mut candidates = units
                    .iter()
                    .enumerate()
                    .filter(|(target_index, _)| {
                        source_kind4_candidate_allowed(
                            units,
                            unit_index,
                            *target_index,
                            source_island,
                            source_owner,
                            source_position,
                            diplomacy,
                        )
                    })
                    .filter_map(|(target_index, target)| {
                        let metric = crate::source_route::source_target_metric(
                            source_position,
                            (target.tile_x, target.tile_y),
                        );
                        source_kind4_candidate_score(attacker, target, metric).map(|score| {
                            (
                                std::cmp::Reverse(score),
                                target.source_runtime_slot.unwrap_or(u16::MAX),
                                target_index,
                                target_index,
                            )
                        })
                    })
                    .collect::<Vec<_>>();
                candidates.sort_unstable();
                candidates.into_iter().find_map(|(_, _, _, target_index)| {
                    source_kind4_candidate_terrain_allowed(
                        &units[unit_index],
                        &units[target_index],
                        island_maps,
                    )
                    .then_some(target_index)
                })
            }
        } else {
            existing_target.filter(|&target_index| {
                source_kind4_candidate_allowed(
                    units,
                    unit_index,
                    target_index,
                    source_island,
                    source_owner,
                    source_position,
                    diplomacy,
                )
            })
        };

        let Some(target_index) = selected else {
            units[unit_index].combat_target = -1;
            continue;
        };
        let target_position = (units[target_index].tile_x, units[target_index].tile_y);
        let target_changed = units[unit_index].combat_target != target_index as i32;
        let unit = &mut units[unit_index];
        unit.combat_target = target_index as i32;
        unit.target_x = target_position.0;
        unit.target_y = target_position.1;
        if target_changed {
            unit.source_route_retry_count = 0;
            unit.source_idle_remaining = 0.0;
            unit.clear_source_route_program();
        }
    }
}

fn source_kind4_candidate_terrain_allowed(
    attacker: &MilitaryUnit,
    target: &MilitaryUnit,
    island_maps: &[crate::island_map::IslandMap],
) -> bool {
    let Some(island_id) = attacker.source_island_id else {
        return true;
    };
    island_maps
        .iter()
        .find(|map| map.island_id == island_id)
        .map(|map| {
            map.source_kind4_line_of_fire_clear(
                (attacker.tile_x, attacker.tile_y),
                (target.tile_x, target.tile_y),
            )
        })
        .unwrap_or(true)
}

fn source_kind4_candidate_allowed(
    units: &[MilitaryUnit],
    unit_index: usize,
    target_index: usize,
    source_island: Option<u8>,
    source_owner: u8,
    source_position: (i32, i32),
    diplomacy: &DiplomacyMatrix,
) -> bool {
    let Some(target) = units.get(target_index) else {
        return false;
    };
    unit_index != target_index
        && target.is_alive()
        && is_source_kind4_land_figure(target)
        && target.source_island_id == source_island
        && target.owner != source_owner
        && diplomacy.get(source_owner, target.owner) != Diplomacy::Allied
        && source_position.0.abs_diff(target.tile_x) <= SOURCE_COMBAT_CANDIDATE_AXIS_LIMIT
        && source_position.1.abs_diff(target.tile_y) <= SOURCE_COMBAT_CANDIDATE_AXIS_LIMIT
}

/// Score a type-4 candidate exactly along the type-4 branch of
/// `FUN_00454250`. The four lookup tables are generated at startup by
/// `FUN_00442a90`; this evaluates the same integer-linear segments directly,
/// including the zero-filled tail after the final distance segment.
fn source_kind4_candidate_score(
    attacker: &MilitaryUnit,
    target: &MilitaryUnit,
    candidate_metric: u32,
) -> Option<u16> {
    let attacker_definition = source_kind4_definition(attacker)?;
    let target_definition = source_kind4_definition(target)?;
    let attacker_shot_radius = u32::from(attacker_definition.source_runtime_shot_radius());
    if candidate_metric > attacker_shot_radius + SOURCE_KIND4_CANDIDATE_SCORE_RADIUS_MARGIN {
        return None;
    }

    let attacker_max_energy = u32::from(attacker_definition.source_runtime_energy_cap());
    let target_max_energy = u32::from(target_definition.source_runtime_energy_cap());
    let attacker_strength = source_kind4_attacker_strength(attacker, attacker_definition);
    let target_strength = source_kind4_target_strength(target, target_definition);
    let target_energy = u32::from(target.source_energy);
    let target_shot_radius = u32::from(target_definition.source_runtime_shot_radius());

    let depleted_ratio = target_energy.saturating_sub(attacker_strength) * 128 / target_max_energy;
    let mut score = u32::from(source_kind4_curve_depleted(depleted_ratio as usize));
    let attacker_ratio = attacker_strength * 128 / target_max_energy;
    score += u32::from(source_kind4_curve_attacker(
        attacker_ratio.min(0x100) as usize,
    ));
    if candidate_metric <= target_shot_radius {
        let retaliation_ratio = target_strength * 128 / attacker_max_energy;
        score += u32::from(source_kind4_curve_retaliation(
            retaliation_ratio.min(0x100) as usize,
        ));
    }

    let approach_distance = candidate_metric.saturating_sub(attacker_shot_radius);
    score += u32::from(source_kind4_curve_approach(approach_distance as usize));
    if target_shot_radius < attacker_shot_radius {
        score += 35;
    }
    Some(score as u16)
}

fn source_kind4_definition(unit: &MilitaryUnit) -> Option<LandFigureDefinition> {
    unit.source_figure_definition_id
        .and_then(LandFigureDefinition::from_id)
}

/// Build the ware and exact quantity written by `FUN_00458000` for a
/// boarding type-4 figure. The source derives the ware from the low byte of
/// its compiled land-figure definition and scales the live energy to one
/// `0x640` cargo entry by that definition's runtime energy cap.
pub fn source_kind4_boarding_cargo(unit: &MilitaryUnit) -> Option<(u8, u16)> {
    let definition = source_kind4_definition(unit)?;
    let ware = u8::try_from(definition.id).ok()?.checked_add(0x18)?;
    let quantity = (u32::from(unit.source_energy)
        * u32::from(SOURCE_SHIP_CARGO_SLOT_QUANTITY_CAPACITY)
        / u32::from(definition.source_runtime_energy_cap())) as u16;
    Some((ware, quantity))
}

