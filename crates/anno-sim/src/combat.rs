impl SourceKind4DispatchState {
    /// Construct the source dispatch globals from the raw `PLAYER4 + 4`
    /// faction bytes. The source's current local player is the configured
    /// human slot (`0`), falling back to slot zero for malformed records.
    pub fn from_player4_faction_states(
        faction_states: [u8; SOURCE_KIND4_PLAYER_SLOT_COUNT],
    ) -> Self {
        let active_player_slot = faction_states
            .iter()
            .position(|&state| state == 0)
            .unwrap_or(0) as u8;
        Self {
            active_player_slot,
            single_player: true,
            remote_owner_dispatch_enabled: false,
            faction_states,
        }
    }

    /// `FUN_00456d00`'s early terminal-program condition. In a multiplayer
    /// session every non-local owner defers; in single-player it defers only
    /// for a source player state outside the active `0x0b..=0x0e` range.
    pub fn defers_terminal_program(self, owner: u8) -> bool {
        owner != self.active_player_slot
            && (!self.single_player
                || !self
                    .faction_states
                    .get(usize::from(owner))
                    .is_some_and(|state| (0x0b..=0x0e).contains(state)))
    }

    /// Apply `FUN_00445930`'s terminal figure-control gate. The active owner
    /// is always permitted. Other owners require `DAT_005bafc8`, initialized
    /// when `DAT_005bafdc < 2`, and a player state in `0x09` or
    /// `0x0b..=0x0e`. `FUN_00446020` also tests the per-player figure count
    /// for state `0x0b`, but that clause is subsumed here by the preceding
    /// inclusive `0x0b..=0x0e` source range.
    pub fn allows_terminal_figure_control(self, attacker_owner: u8) -> bool {
        attacker_owner == self.active_player_slot
            || (self.single_player
                && self
                    .faction_states
                    .get(usize::from(attacker_owner))
                    .is_some_and(|state| *state == 0x09 || (0x0b..=0x0e).contains(state)))
    }
}

