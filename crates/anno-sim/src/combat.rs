/// As [`tick_unit_orders_with_maps_and_source_rand_and_dispatch_state`], with
/// `FUN_00444fe0` geometry for target descriptors backed by live state outside
/// an [`crate::island_map::IslandMap`].
pub fn tick_unit_orders_with_maps_and_source_rand_and_dispatch_state_and_target_resolver(
    units: &mut [MilitaryUnit],
    dt_ms: u32,
    ocean_map: Option<&crate::ocean_map::OceanMap>,
    island_maps: &[crate::island_map::IslandMap],
    source_rand: &mut SourceRand,
    dispatch_state: SourceKind4DispatchState,
    mut resolve_target: impl FnMut(SourceTargetDescriptor) -> Option<SourcePathTargetRect>,
) {
    for u in units.iter_mut() {
        if !u.is_alive() {
            continue;
        }
        if tick_source_kind4_order(
            u,
            dt_ms,
            island_maps,
            source_rand,
            dispatch_state,
            &mut resolve_target,
        ) {
            continue;
        }
        if u.combat_target >= 0 {
            continue;
        }
        if u.tile_x == u.target_x && u.tile_y == u.target_y {
            u.move_timer_ms = 0;
            // Patrol advance: when a waypoint is reached and the
            // unit has a patrol list, retarget the next waypoint
            // (round-robin). Manual sec. 9.2.4 "Patrol".
            if !u.patrol.is_empty() {
                u.patrol_idx = (u.patrol_idx + 1) % u.patrol.len() as u32;
                let (nx, ny) = u.patrol[u.patrol_idx as usize];
                u.target_x = nx;
                u.target_y = ny;
            } else {
                continue;
            }
        }
        let speed = u.unit_type.stats().move_speed.max(1) as u32;
        let step_ms = (1000 / speed).max(100);
        u.move_timer_ms = u.move_timer_ms.saturating_add(dt_ms);
        while u.move_timer_ms >= step_ms {
            u.move_timer_ms -= step_ms;
            let Some((nx, ny)) = next_order_step(u, ocean_map, island_maps) else {
                break;
            };
            let sx = (nx - u.tile_x).signum();
            let sy = (ny - u.tile_y).signum();
            u.tile_x = nx;
            u.tile_y = ny;
            u.direction = match (sx, sy) {
                (0, -1) => 0,
                (1, -1) => 1,
                (1, 0) => 2,
                (1, 1) => 3,
                (0, 1) => 4,
                (-1, 1) => 5,
                (-1, 0) => 6,
                (-1, -1) => 7,
                _ => u.direction,
            };
        }
    }
}

/// Advance a source type-4 land figure with the executable's continuous
/// motion model. `FUN_00457ce0` derives the velocity from the figure's
/// `Speed` and current `Wegspeed[Speedtyp]`; `FUN_00451890` consumes
/// `dt_ms * 0.05` until that route cell is exhausted.
///
/// Returns true only for a source type-4 figure with a live runtime slot.
/// Other units retain the local compatibility mover below.
fn tick_source_kind4_order(
    unit: &mut MilitaryUnit,
    dt_ms: u32,
    island_maps: &[crate::island_map::IslandMap],
    source_rand: &mut SourceRand,
    dispatch_state: SourceKind4DispatchState,
    resolve_target: &mut impl FnMut(SourceTargetDescriptor) -> Option<SourcePathTargetRect>,
) -> bool {
    if unit.source_runtime_slot.is_none() {
        return false;
    }
    let Some(definition) = unit
        .source_figure_definition_id
        .and_then(anno_formats::szs::LandFigureDefinition::from_id)
    else {
        return false;
    };
    let Some(island_id) = unit.source_island_id else {
        return false;
    };
    let Some(map) = island_maps.iter().find(|map| map.island_id == island_id) else {
        return false;
    };

    if !unit.source_position_initialized {
        unit.source_position_x = unit.tile_x as f32 * 0.5 + 0.25;
        unit.source_position_y = unit.tile_y as f32 * 0.5 + 0.25;
        unit.source_position_initialized = true;
    }

    let mut remaining_time = dt_ms as f32 * SOURCE_MOTION_TIME_SCALE;
    while remaining_time > 0.0 {
        if unit.source_motion_target.is_none() && unit.source_idle_remaining > 0.0 {
            let consumed = remaining_time.min(
                unit.source_idle_remaining / SOURCE_KIND4_TERMINAL_IDLE_RATE,
            );
            unit.source_idle_remaining =
                (unit.source_idle_remaining - consumed * SOURCE_KIND4_TERMINAL_IDLE_RATE).max(0.0);
            remaining_time -= consumed;
            if unit.source_idle_remaining > f32::EPSILON {
                break;
            }
            unit.source_idle_remaining = 0.0;
        }

        if unit.source_step_remaining <= 0.0 || unit.source_motion_target.is_none() {
            if source_kind4_program_is_terminal(unit)
                && dispatch_state.defers_terminal_program(unit.owner)
            {
                unit.source_idle_remaining = SOURCE_KIND4_DEFERRED_IDLE_REMAINING;
                continue;
            }
            if source_kind4_terminal_target_reached_with_target_resolver(
                unit,
                map,
                &mut *resolve_target,
            ) {
                unit.source_target_descriptor = None;
                unit.target_x = unit.tile_x;
                unit.target_y = unit.tile_y;
            }
            let has_live_source_target = unit
                .source_target_descriptor
                .and_then(|descriptor| {
                    map.source_land_target_rect(descriptor)
                        .or_else(|| resolve_target(descriptor))
                })
                .is_some();
            if !has_live_source_target
                && unit.tile_x == unit.target_x
                && unit.tile_y == unit.target_y
            {
                unit.move_timer_ms = 0;
                if unit.patrol.is_empty() {
                    unit.source_idle_remaining = SOURCE_KIND4_TERMINAL_IDLE_REMAINING;
                    continue;
                }
                unit.patrol_idx = (unit.patrol_idx + 1) % unit.patrol.len() as u32;
                let (next_x, next_y) = unit.patrol[unit.patrol_idx as usize];
                unit.target_x = next_x;
                unit.target_y = next_y;
                unit.source_route_retry_count = 0;
                unit.source_idle_remaining = 0.0;
                unit.clear_source_route_program();
            }

            let next = match source_kind4_next_program_run_endpoint(unit) {
                Some(next) => next,
                None => {
                    let Some(program) = source_kind4_route_program_with_target_resolver(
                        unit,
                        map,
                        definition.source_speed_type(),
                        definition.source_max_step_count(),
                        unit.source_route_radius,
                        unit.source_route_retry_count,
                        source_rand,
                        &mut *resolve_target,
                    ) else {
                        unit.source_route_retry_count = unit.source_route_retry_count.wrapping_add(1);
                        unit.source_idle_remaining = SOURCE_KIND4_TERMINAL_IDLE_REMAINING;
                        continue;
                    };
                    install_source_kind4_route_program(unit, &program);
                    let Some(next) = source_kind4_next_program_run_endpoint(unit) else {
                        unit.source_route_retry_count = unit.source_route_retry_count.wrapping_add(1);
                        unit.source_idle_remaining = SOURCE_KIND4_TERMINAL_IDLE_REMAINING;
                        continue;
                    };
                    next
                }
            };
            let (step_x, step_y) = (
                (next.0 - unit.tile_x).signum(),
                (next.1 - unit.tile_y).signum(),
            );
            unit.direction = match (step_x, step_y) {
                (0, -1) => 0,
                (1, -1) => 1,
                (1, 0) => 2,
                (1, 1) => 3,
                (0, 1) => 4,
                (-1, 1) => 5,
                (-1, 0) => 6,
                (-1, -1) => 7,
                _ => unit.direction,
            };
            let cardinal_distance = (next.0 - unit.tile_x)
                .unsigned_abs()
                .max((next.1 - unit.tile_y).unsigned_abs())
                as f32
                * 0.5;
            unit.source_step_remaining = if step_x != 0 && step_y != 0 {
                cardinal_distance * SOURCE_DIAGONAL_DISTANCE
            } else {
                cardinal_distance
            };
            unit.source_motion_target = Some(next);
        }

        let Some(local) = map.source_world_to_local((unit.tile_x, unit.tile_y)) else {
            break;
        };
        let Some(terrain_wegspeed) =
            map.source_land_movement_speed(definition.source_speed_type(), local)
        else {
            break;
        };
        let rate = definition.source_move_speed() as f32 * SOURCE_FIGURE_SPEED_SCALE * 32.0
            / terrain_wegspeed.max(1) as f32;
        if rate <= 0.0 {
            break;
        }

        let consumed = remaining_time.min(unit.source_step_remaining / rate);
        let distance = consumed * rate;
        let Some(next) = unit.source_motion_target else {
            unit.source_step_remaining = 0.0;
            continue;
        };
        let step_x = (next.0 - unit.tile_x).signum() as f32;
        let step_y = (next.1 - unit.tile_y).signum() as f32;
        let divisor = if step_x != 0.0 && step_y != 0.0 {
            SOURCE_DIAGONAL_DISTANCE
        } else {
            1.0
        };
        unit.source_position_x += step_x * distance / divisor;
        unit.source_position_y += step_y * distance / divisor;
        unit.source_step_remaining -= distance;
        remaining_time -= consumed;

        if unit.source_step_remaining <= f32::EPSILON {
            unit.source_step_remaining = 0.0;
            unit.source_motion_target = None;
            unit.tile_x = next.0;
            unit.tile_y = next.1;
            unit.source_position_x = unit.tile_x as f32 * 0.5 + 0.25;
            unit.source_position_y = unit.tile_y as f32 * 0.5 + 0.25;
        }
    }
    true
}

/// Build the full `FUN_004581f0` direction program. Each output byte packs a
/// direction and a run length; `FUN_0046cf70` begins a new byte whenever the
/// direction or low-seven-bit terrain class changes, or `Maxstepcnt` is met.
fn source_kind4_route_program(
    unit: &MilitaryUnit,
    map: &crate::island_map::IslandMap,
    speed_type: u8,
    max_step_count: u8,
    route_radius: u8,
    retry_count: u8,
    source_rand: &mut SourceRand,
) -> Option<Vec<u8>> {
    source_kind4_route_program_with_target_resolver(
        unit,
        map,
        speed_type,
        max_step_count,
        route_radius,
        retry_count,
        source_rand,
        |_| None,
    )
}

/// `FUN_004581f0` routes against the rectangle resolved by `FUN_00444fe0`.
/// Static and packed descriptors resolve from the island map; object-backed
/// descriptors are supplied by the owning live-state table.
fn source_kind4_route_program_with_target_resolver(
    unit: &MilitaryUnit,
    map: &crate::island_map::IslandMap,
    speed_type: u8,
    max_step_count: u8,
    route_radius: u8,
    retry_count: u8,
    source_rand: &mut SourceRand,
    mut resolve_target: impl FnMut(SourceTargetDescriptor) -> Option<SourcePathTargetRect>,
) -> Option<Vec<u8>> {
    let start = (unit.tile_x, unit.tile_y);
    let target = unit
        .source_target_descriptor
        .and_then(|descriptor| {
            map.source_land_target_rect(descriptor)
                .or_else(|| resolve_target(descriptor))
        })
        .or_else(|| {
            crate::source_route::SourcePathTargetRect::new(
                (unit.target_x, unit.target_y),
                1,
                1,
            )
        })?;
    if target.contains(start) {
        return None;
    }
    let window_center = source_kind4_route_window_center(
        start,
        route_radius,
        retry_count,
        source_rand,
    )?;
    let mut grid = map
        .source_land_path_grid(speed_type)?
        .source_window(window_center, usize::from(route_radius))?;
    let (mut steps, reached) = match grid.search_threshold_target(start, target, 7, 0) {
        Ok(result) => (result.steps, result.position),
        Err(crate::source_route::SourcePathSearchError::NoRoute) => {
            let marker = grid.nearest_reached_marker(
                target.nearest_point(start),
                i32::from(crate::ocean_map::SOURCE_WORLD_WIDTH),
            )?;
            let mut steps = grid.steps_to_reached_marker(start, marker)?;
            if !map.source_land_partial_marker_allowed(marker) {
                steps.pop()?;
            }
            let reached = source_steps_endpoint(start, &steps)?;
            let clamped_target = target.nearest_point(start);
            (crate::source_route::source_target_metric(reached, clamped_target)
                < crate::source_route::source_target_metric(start, clamped_target))
                .then_some((steps, reached))?
        }
        Err(crate::source_route::SourcePathSearchError::OutOfBounds) => return None,
    };
    if !map.source_land_partial_marker_allowed(reached) {
        steps.pop()?;
    }
    let program = source_kind4_encode_route_program(&steps, max_step_count);
    (!program.is_empty()).then_some(program)
}

/// `FUN_0046cf70` leaves the final byte of the caller's 0x80-byte buffer for
/// its `0xc1` terminator. It groups predecessor steps by direction and
/// low-seven-bit terrain class, splitting at the figure's `Maxstepcnt`.
fn source_kind4_encode_route_program(
    steps: &[crate::source_route::SourceRouteStep],
    max_step_count: u8,
) -> Vec<u8> {
    let mut program = Vec::new();
    let max_step_count = usize::from(max_step_count.max(1));
    let mut previous_direction = None;
    let mut previous_terrain_class = None;
    let mut run_length = 0usize;
    for step in steps {
        let terrain_class = step.metadata & 0x7f;
        let extends_last = previous_direction == Some(step.direction)
            && previous_terrain_class == Some(terrain_class)
            && run_length < max_step_count
            && run_length < 0x0f;
        if extends_last {
            let previous_run = program
                .last_mut()
                .expect("a matching prior direction has an encoded run");
            *previous_run += 1;
            run_length += 1;
        } else {
            if program.len() >= SOURCE_KIND4_ROUTE_PROGRAM_CAPACITY - 1 {
                break;
            }
            program.push(step.direction << 4 | 1);
            previous_direction = Some(step.direction);
            previous_terrain_class = Some(terrain_class);
            run_length = 1;
        }
    }
    program
}

fn install_source_kind4_route_program(unit: &mut MilitaryUnit, program: &[u8]) {
    unit.clear_source_route_program();
    let count = program
        .len()
        .min(SOURCE_KIND4_ROUTE_PROGRAM_CAPACITY.saturating_sub(1));
    unit.source_route_program[..count].copy_from_slice(&program[..count]);
    unit.source_route_program[count] = SOURCE_KIND4_ROUTE_PROGRAM_TERMINATOR;
}

fn source_kind4_next_program_run_endpoint(unit: &mut MilitaryUnit) -> Option<(i32, i32)> {
    let command = *unit
        .source_route_program
        .get(usize::from(unit.source_route_program_cursor))?;
    if command & 0xf0 == 0xc0 || command & 0x0f == 0 {
        return None;
    }
    let (dx, dy) = crate::source_route::source_direction_delta(command >> 4)?;
    let run_length = i32::from(command & 0x0f);
    unit.source_route_program_cursor = unit.source_route_program_cursor.checked_add(1)?;
    Some((
        unit.tile_x.checked_add(dx.checked_mul(run_length)?)?,
        unit.tile_y.checked_add(dy.checked_mul(run_length)?)?,
    ))
}

fn source_kind4_program_is_terminal(unit: &MilitaryUnit) -> bool {
    unit.source_route_program
        .get(usize::from(unit.source_route_program_cursor))
        .map_or(true, |command| command & 0xf0 == 0xc0 || command & 0x0f == 0)
}

/// `FUN_00456d00` clears a resolved terminal descriptor only when
/// `FUN_00443440` accepts its descriptor-specific weighted-distance limit.
/// The local type-4 state retains raw coordinates for packed `0x37`/`0x38`
/// descriptors and for the `0x34` native-idle static cell written by
/// `FUN_004458f0`.
fn source_kind4_terminal_target_reached(
    unit: &MilitaryUnit,
    map: &crate::island_map::IslandMap,
) -> bool {
    source_kind4_terminal_target_reached_with_target_resolver(unit, map, |_| None)
}

/// Apply the terminal `FUN_00443440` gate after resolving an object-backed
/// descriptor through the corresponding live source table.
fn source_kind4_terminal_target_reached_with_target_resolver(
    unit: &MilitaryUnit,
    map: &crate::island_map::IslandMap,
    mut resolve_target: impl FnMut(SourceTargetDescriptor) -> Option<SourcePathTargetRect>,
) -> bool {
    unit.source_target_descriptor
        .and_then(|descriptor| {
            map.source_land_target_rect(descriptor)
                .or_else(|| resolve_target(descriptor))
                .map(|target| (descriptor, target))
        })
        .is_some_and(|(descriptor, target)| {
            crate::source_route::source_target_metric(
                (unit.tile_x, unit.tile_y),
                target.nearest_point((unit.tile_x, unit.tile_y)),
            ) <= source_kind4_terminal_distance_limit(descriptor)
        })
}

/// `FUN_00456d00` selects this `FUN_00443440` limit from the descriptor
/// kind immediately before clearing the terminal state descriptor.
const fn source_kind4_terminal_distance_limit(descriptor: SourceTargetDescriptor) -> u32 {
    match descriptor.kind() {
        1 => 9,
        0x32 | 0x33 => 1,
        0x34 => 2,
        _ => 0,
    }
}

